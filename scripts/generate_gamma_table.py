#!/usr/bin/env python3
import argparse

def gamma_correct(norm: float, gamma: float) -> int:
    corrected = norm ** gamma
    return int(corrected * 65535 + 0.5)

def generate_table(points: int, gamma: float) -> list[int]:
    return [gamma_correct(i / (points - 1), gamma) for i in range(points)]

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True)
    parser.add_argument("--points", type=int, required=True)
    parser.add_argument("--gamma", type=float, required=True)
    args = parser.parse_args()

    print(f"Generating {args.output}...")

    table = generate_table(args.points, args.gamma)
    values = ",\n    ".join(str(v) for v in table)

    header = f"""// AUTO-GENERATED FILE. DO NOT EDIT.
// Generated by generate_gamma_table.py
#pragma once

#include <cstdint>
#include <array>

inline constexpr auto gamma_table = std::array<std::uint32_t, {len(table)}>{{
    {values}
}};
"""

    with open(args.output, "w") as file:
        file.write(header)

if __name__ == "__main__":
    main()