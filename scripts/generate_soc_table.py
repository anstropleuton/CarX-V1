#!/usr/bin/env python3
import argparse
import math

def sigmoid(x: float, k: float) -> float:
    return 1.0 / (1.0 + math.exp(-k * (x - 0.5)))

def generate_table(points: int, steepness: float) -> list[float]:
    return [sigmoid(i / (points - 1), steepness) for i in range(points)]

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True)
    parser.add_argument("--points", type=int, required=True)
    parser.add_argument("--steepness", type=float, required=True)
    args = parser.parse_args()

    print(f"Generating {args.output}...")

    table = generate_table(args.points, args.steepness)
    values = ",\n    ".join(f"{v:.9f}F" for v in table)

    header = f"""// AUTO-GENERATED FILE. DO NOT EDIT.
// Generated by generate_soc_table.py
#pragma once

#include <array>

inline constexpr auto soc_table = std::array<float, {args.points}>{{
    {values}
}};
"""

    with open(args.output, "w") as file:
        file.write(header)

if __name__ == "__main__":
    main()